"""Domain exceptions for Ruiru Titans AI Assistant and Guardrails."""


class AIInputValidationError(Exception):
    """Raised when user input violates safety rules, bounds, or prompt-injection guardrails."""


class AIProviderError(Exception):
    """Raised when an external LLM provider encounters a fatal error."""


class AIProviderRateLimitError(AIProviderError):
    """Raised when an external LLM provider returns a 429 / RESOURCE_EXHAUSTED."""


class AIProviderConfigurationError(AIProviderError):
    """Raised when API keys or provider models are not properly configured."""


class AIToolExecutionError(Exception):
    """Raised when an MCP tool invocation fails critically during orchestration."""


class AIGroundingVerificationError(Exception):
    """Raised when factual assertions generated by the model fail verification against tool results."""
